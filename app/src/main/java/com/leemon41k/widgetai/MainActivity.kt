@Composable
private fun AnimatedGeometryBackground() {
    val transition = rememberInfiniteTransition(label = "geometry")
    val phase by transition.animateFloat(0f, (Math.PI * 2).toFloat(),
        infiniteRepeatable(tween(18000, easing = LinearEasing), RepeatMode.Restart), label = "phase")
    Canvas(Modifier.fillMaxSize().alpha(.92f)) {
        val w = size.width; val h = size.height
        for (i in 0 until 54) {
            val bx = ((i * 79) % 101) / 100f * w
            val by = ((i * 137) % 103) / 103f * h
            val x = bx + sin(phase + i * .53f) * 23f
            val y = by + cos(phase * .7f + i) * 17f
            val length = 22f + ((i * 17) % 48)
            val angle = sin(phase * .6f + i * .41f) * .8f
            val ex = x + sin(angle) * length; val ey = y + cos(angle) * length
            val color = if (i % 3 != 2) Red.copy(alpha = .17f) else Color.White.copy(alpha = .13f)
            drawLine(color, androidx.compose.ui.geometry.Offset(x, y), androidx.compose.ui.geometry.Offset(ex, ey), if (i % 5 == 0) 2.1f else 1.25f)
            if (i % 4 == 0) drawCircle(color, 2.2f + (i % 3), androidx.compose.ui.geometry.Offset(ex, ey))
            if (i % 9 == 0) drawCircle(Red.copy(alpha = .075f), 12f + (i % 4) * 4f,
                androidx.compose.ui.geometry.Offset(x + 15f, y - 10f), style = Stroke(1.2f))
        }
        for (i in 0 until 5) {
            val cx = w * (.15f + i * .18f) + sin(phase + i) * 12f
            val cy = h * (.22f + (i % 3) * .25f) + cos(phase + i * .7f) * 15f
            val r = 18f + i * 5f
            val path = Path().apply { moveTo(cx, cy-r); lineTo(cx+r, cy); lineTo(cx, cy+r); lineTo(cx-r, cy); close() }
            drawPath(path, if (i % 2 == 0) Red.copy(alpha = .10f) else Color.White.copy(alpha = .07f), style = Stroke(1.1f))
        }
    }
}

@Composable
private fun vectorFieldColors() = OutlinedTextFieldDefaults.colors(
    focusedTextColor = SoftWhite, unfocusedTextColor = SoftWhite,
    focusedBorderColor = Red, unfocusedBorderColor = Color.White.copy(alpha = .22f),
    cursorColor = Red, focusedPlaceholderColor = Muted, unfocusedPlaceholderColor = Muted
)

private fun hasInternet(context: Context): Boolean {
    val cm = context.getSystemService(Context.CONNECTIVITY_SERVICE) as android.net.ConnectivityManager
    val network = cm.activeNetwork ?: return false
    val caps = cm.getNetworkCapabilities(network) ?: return false
    return caps.hasCapability(android.net.NetworkCapabilities.NET_CAPABILITY_INTERNET) &&
        caps.hasCapability(android.net.NetworkCapabilities.NET_CAPABILITY_VALIDATED)
}

private fun loadLibrary(prefs: android.content.SharedPreferences): List<WidgetDefinition> {
    val raw = prefs.getString("library", "[]") ?: "[]"
    return runCatching {
        val array = JSONArray(raw)
        (0 until array.length()).mapNotNull { index ->
            WidgetDefinition.fromJson(array.optJSONObject(index) ?: return@mapNotNull null)
        }
    }.getOrDefault(emptyList())
}

private fun saveLibrary(prefs: android.content.SharedPreferences, items: List<WidgetDefinition>) {
    val array = JSONArray()
    items.forEach { array.put(it.toJson()) }
    prefs.edit().putString("library", array.toString()).apply()
}
