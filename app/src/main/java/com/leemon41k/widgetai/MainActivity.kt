            Spacer(Modifier.height(10.dp))
            Text("Опиши, что должно появиться на главном экране.", color = Muted, fontSize = 14.sp)
            Spacer(Modifier.height(24.dp))
            Surface(color = Panel.copy(alpha = .94f), shape = RoundedCornerShape(18.dp)) {
                Column(Modifier.padding(16.dp)) {
                    Text("НОВЫЙ ВИДЖЕТ", color = Muted, fontSize = 11.sp, letterSpacing = 1.7.sp, fontWeight = FontWeight.Bold)
                    Spacer(Modifier.height(12.dp))
                    OutlinedTextField(
                        value = prompt, onValueChange = onPrompt, modifier = Modifier.fillMaxWidth(),
