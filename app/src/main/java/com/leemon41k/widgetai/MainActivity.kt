        }
        Row(Modifier.fillMaxWidth().padding(top = 10.dp, bottom = 14.dp), horizontalArrangement = Arrangement.SpaceBetween) {
            Text("Мои виджеты", color = SoftWhite, fontSize = 13.sp, modifier = Modifier.clickable(onClick = onLibrary).padding(8.dp))
            Text("Настройки", color = Muted, fontSize = 13.sp, modifier = Modifier.clickable(onClick = onSettings).padding(8.dp))
        }
    }
}

@Composable
private fun WidgetPreview(widget: WidgetDefinition) {
    Surface(color = Color(0xFF171717), shape = RoundedCornerShape(18.dp)) {
        Column(Modifier.fillMaxWidth().padding(16.dp)) {
            Text("ПРЕДПРОСМОТР", color = Muted, fontSize = 10.sp, letterSpacing = 1.5.sp)
            Spacer(Modifier.height(8.dp))
            Text(widget.name, color = SoftWhite, fontSize = 18.sp, fontWeight = FontWeight.SemiBold)
            if (widget.description.isNotBlank()) Text(widget.description, color = Muted, fontSize = 12.sp)
            Spacer(Modifier.height(10.dp))
            widget.elements.forEach { element ->
                val color = runCatching { Color(android.graphics.Color.parseColor(element.color)) }.getOrDefault(SoftWhite)
                Text(if (element.label.isBlank()) element.value else "${element.label}: ${element.value}",
                    color = color, fontSize = element.size.coerceIn(10, 32).sp, modifier = Modifier.padding(vertical = 3.dp))
            }
        }
    }
}

@Composable
