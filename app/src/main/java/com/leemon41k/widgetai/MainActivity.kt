                            Text(item.description.ifBlank { "${item.elements.size} элементов" }, color = Muted, fontSize = 12.sp)
                        }
                    }
                }
            }
        }
        Text("Назад", color = Red, modifier = Modifier.clickable(onClick = onBack).padding(vertical = 18.dp))
    }
}

