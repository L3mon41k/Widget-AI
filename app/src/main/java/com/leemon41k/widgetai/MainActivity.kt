                    Button(onClick = onGenerate, enabled = !busy,
                        modifier = Modifier.fillMaxWidth().height(52.dp),
                        shape = RoundedCornerShape(14.dp),
                        colors = ButtonDefaults.buttonColors(containerColor = Red, disabledContainerColor = Color(0xFF552326))) {
                        if (busy) CircularProgressIndicator(Modifier.size(18.dp), color = Color.White, strokeWidth = 2.dp)
                        else Text("Создать с помощью ИИ", fontWeight = FontWeight.SemiBold)
                    }
                }
            }
            Spacer(Modifier.height(14.dp))
            Text(status, color = Muted, fontSize = 13.sp, lineHeight = 19.sp)
            generated?.let {
                Spacer(Modifier.height(14.dp))
