@Composable
private fun WidgetAIApp() {
    val context = LocalContext.current
    val prefs = remember { context.getSharedPreferences("widgetai", Context.MODE_PRIVATE) }
    var page by rememberSaveable { mutableStateOf("create") }
    var prompt by rememberSaveable { mutableStateOf("") }
    var apiUrl by rememberSaveable { mutableStateOf(prefs.getString("api_url", "") ?: "") }
    var status by rememberSaveable { mutableStateOf("Опиши виджет, который хочешь создать") }
    var busy by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf<WidgetDefinition?>(null) }
    var library by remember { mutableStateOf(loadLibrary(prefs)) }
    val scope = rememberCoroutineScope()

    BackHandler(page != "create") { page = "create" }
    Box(Modifier.fillMaxSize().background(Black)) {
        AnimatedGeometryBackground()
        Column(Modifier.fillMaxSize().statusBarsPadding().imePadding()) {
            Row(
                Modifier.fillMaxWidth().padding(start = 20.dp, end = 20.dp, top = 14.dp, bottom = 12.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Canvas(Modifier.size(42.dp).clickable { page = if (page == "menu") "create" else "menu" }) {
                    drawLine(SoftWhite, androidx.compose.ui.geometry.Offset(3f, size.height * .35f),
                        androidx.compose.ui.geometry.Offset(size.width - 3f, size.height * .35f), 2.2f)
                    drawLine(SoftWhite, androidx.compose.ui.geometry.Offset(3f, size.height * .68f),
                        androidx.compose.ui.geometry.Offset(size.width - 3f, size.height * .68f), 2.2f)
                }
                Spacer(Modifier.width(12.dp))
                Text("WIDGETAI", color = SoftWhite, fontSize = 13.sp, letterSpacing = 4.sp, fontWeight = FontWeight.Bold)
                Spacer(Modifier.weight(1f))
                Text("●", color = if (apiUrl.startsWith("https://")) Red else Muted, fontSize = 13.sp)
            }
            when (page) {
                "menu" -> MenuScreen(onCreate = { page = "create" }, onLibrary = { page = "library" }, onSettings = { page = "settings" })
                "library" -> LibraryScreen(library, onOpen = { generated = it; page = "create" }, onBack = { page = "create" })
                "settings" -> SettingsScreen(apiUrl, onApiUrl = { apiUrl = it }, onSave = {
                    prefs.edit().putString("api_url", apiUrl.trim().trimEnd('/')).apply()
                    status = "Адрес сервера сохранён"
                    page = "create"
                }, onBack = { page = "create" })
                else -> CreateScreen(
                    prompt = prompt, onPrompt = { prompt = it }, status = status, busy = busy,
                    generated = generated, onGenerate = {
                        if (prompt.isBlank()) {
                            status = "Сначала опиши свой виджет"
                        } else if (!hasInternet(context)) {
                            status = "Нет подключения к интернету"
                        } else if (apiUrl.isBlank() || !apiUrl.startsWith("https://")) {
                            status = "Сначала укажи HTTPS-адрес сервера в настройках"
                        } else {
                            scope.launch {
                                busy = true
                                status = "Отправляю запрос на сервер…"
                                try {
                                    val result = WidgetApi.generate(apiUrl, prompt.trim(), DeviceData.read(context))
                                    generated = result.widget
                                    status = result.message
                                    val updated = (listOf(result.widget) + library.filterNot { it.name == result.widget.name }).take(30)
                                    library = updated
                                    saveLibrary(prefs, updated)
                                } catch (e: Exception) {
                                    status = "Не удалось создать виджет: ${e.message ?: "ошибка сервера"}"
                                } finally { busy = false }
                            }
                        }
                    },
                    onLibrary = { page = "library" },
                    onSettings = { page = "settings" }
                )
            }
        }
    }
}

@Composable
