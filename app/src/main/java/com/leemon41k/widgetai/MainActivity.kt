    Column(Modifier.fillMaxSize().padding(24.dp)) {
        Text("МЕНЮ", color = Muted, fontSize = 11.sp, letterSpacing = 2.sp, fontWeight = FontWeight.Bold)
        Spacer(Modifier.height(18.dp))
        MenuEntry("Создать виджет", onCreate)
        MenuEntry("Мои виджеты", onLibrary)
        MenuEntry("Настройки", onSettings)
        Spacer(Modifier.weight(1f))
        Text("WidgetAI · 0.2.0 alpha", color = Muted, fontSize = 12.sp)
